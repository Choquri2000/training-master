// Builds js/data/lang/<code>.js from tools/i18n/en.json and the numbered translations in
// tools/i18n/<code>/*.txt (one "number<TAB>translation" per line; a missing line stays English).
// Run: node tools/i18n-build.mjs
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
const dir = new URL('i18n/', import.meta.url);
const en = JSON.parse(readFileSync(new URL('en.json', dir), 'utf8'));
const slots = s => (s.match(/\{\w+\}/g) || []).sort().join();
for (const code of ['es', 'de', 'fr', 'it', 'ru']) {
  const d = new URL(`${code}/`, dir); if (!existsSync(d)) continue;
  const map = {}; let bad = 0;
  for (const f of readdirSync(d).filter(f => f.endsWith('.txt')).sort()) {
    for (const line of readFileSync(new URL(f, d), 'utf8').split('\n')) {
      const m = line.match(/^(\d+)\t(.+)$/); if (!m) continue;
      const src = en[+m[1]], txt = m[2].trim();
      if (src == null) { console.warn(code, 'no English line', m[1]); bad++; continue; }
      if (slots(src) !== slots(txt)) { console.warn(code, m[1], 'slots differ:', src, '|', txt); bad++; continue; }
      map[src] = txt;
    }
  }
  writeFileSync(new URL(`../../js/data/lang/${code}.js`, dir), `// Generated by tools/i18n-build.mjs from tools/i18n/${code}/. Edit those files, not this one.\nexport default ${JSON.stringify(map, null, 0).replace(/","/g, '",\n"')};\n`);
  console.log(code, Object.keys(map).length, 'of', en.length, bad ? `(${bad} skipped)` : '');
}
